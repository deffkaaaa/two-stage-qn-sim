package ua.kpi.modsim;

/**
 * Джерело випадковості моделі. Окремий інтерфейс дає змогу підставити
 * детермінований режим для верифікації (усі розкиди дорівнюють нулю).
 */
public interface Sampler {
    /**
     * Значення величини, розподіленої за експоненціальним законом із середнім mean.
     *
     * @param stream назва потоку випадкових чисел (джерело випадковості): різні потоки незалежні,
     *               а однакові потоки при однаковому seed дають однакові послідовності
     */
    double expo(String stream, double mean);

    /** Чи бракована деталь після обробки; key - назва верстата, p - імовірність браку. */
    boolean defect(String key, double p);

    /** Вибір одного з n одночасних елементів (індекс від 0 до n-1). */
    int pick(int n);
}
